"""The exp table the sampler (and numpy_layer_mh's flowkv path) reads: a max-
shifted score is quantized to q = clamp(round(shifted / exp_quant_scale),
low, 0) and read as exp(q * exp_quant_scale). The kernel's header and the
numpy mirrors come from the same entries, so both read identical values.
"""

import argparse
import sys

import numpy as np


def exp_lut(exp_quant_scale: float, low: int = -128) -> np.ndarray:
    """fp32 exp((q) * exp_quant_scale) for q from `low` to 127, at lut[q - low].

    Args:
        exp_quant_scale: The score units of one index step.
        low: The lowest index; a score quantized below it reads lut[0].

    Returns:
        The 128 - `low` entries.
    """
    out = np.zeros(128 - low, dtype=np.float32)
    for k in range(128 - low):
        out[k] = np.exp((k + low) * exp_quant_scale).astype(np.float32)
    return out


def exp_lut_header(exp_quant_scale: float, low: int = -128) -> str:
    """The C header the kernels include: `exp_lut(exp_quant_scale, low)`,
    LLAMA_EXP_LUT_LOW and LLAMA_EXP_QUANT_SCALE."""
    raw = exp_lut(exp_quant_scale, low).view(np.uint32)
    lines = [
        "// auto-generated by gen_exp_lut.py; do not edit",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define LLAMA_EXP_QUANT_SCALE {float(exp_quant_scale)!r}f",
        f"#define LLAMA_EXP_LUT_LOW ({low})",
        f"static const uint32_t llama_exp_lut_raw[{len(raw)}] = {{",
    ]
    for i in range(0, len(raw), 4):
        lines.append(
            "    "
            + ", ".join(f"0x{raw[j]:08x}" for j in range(i, min(i + 4, len(raw))))
            + ","
        )
    lines += ["};"]
    return "\n".join(lines) + "\n"


def main():
    p = argparse.ArgumentParser()
    p.add_argument(
        "--exp-quant-scale",
        type=float,
        required=True,
        help="resolution of the LUT in score-units per index step",
    )
    p.add_argument("--low", type=int, default=-128, help="the lowest index")
    p.add_argument("-o", required=True)
    args = p.parse_args(sys.argv[1:])
    with open(args.o, "w") as f:
        f.write(exp_lut_header(args.exp_quant_scale, args.low))


if __name__ == "__main__":
    main()
