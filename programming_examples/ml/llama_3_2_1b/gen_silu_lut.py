"""Codegen: emit a static const bf16[256] SiLU LUT header.

llama_silu_mul_int8.cc and numpy_layer_mh read the same bf16 silu(i *
gate_scale) entries, so the kernel matches its numpy mirror exactly.
"""

import argparse
import sys

import numpy as np
from ml_dtypes import bfloat16


def silu_lut(gate_scale: float) -> np.ndarray:
    """256 bf16 entries: lut[i + 128] = silu(i * gate_scale) for i in int8."""
    out = np.zeros(256, dtype=bfloat16)
    for raw in range(256):
        i = raw - 128
        x = float(i) * gate_scale
        silu = x / (1.0 + np.exp(-x))
        out[raw] = bfloat16(silu)
    return out


def silu_lut_header(gate_scale: float) -> str:
    """The C header the silu kernel includes, holding `silu_lut(gate_scale)`."""
    raw = silu_lut(gate_scale).view(np.uint16)
    lines = [
        "// auto-generated by gen_silu_lut.py; do not edit",
        f"// gate_scale = {gate_scale}",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "static const uint16_t llama_silu_lut_raw[256] = {",
    ]
    for i in range(0, 256, 8):
        lines.append(
            "    " + ", ".join(f"0x{raw[j]:04x}" for j in range(i, i + 8)) + ","
        )
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--gate-scale", type=float, required=True)
    p.add_argument("-o", required=True)
    args = p.parse_args(sys.argv[1:])
    with open(args.o, "w") as f:
        f.write(silu_lut_header(args.gate_scale))


if __name__ == "__main__":
    main()
