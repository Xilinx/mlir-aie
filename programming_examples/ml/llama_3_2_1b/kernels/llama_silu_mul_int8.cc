// Llama silu_mul: fused SiLU(gate) * up, int8 in/out, bf16-internal.
//
//   silu_g = silu_lut[gate_i8 + 128]            (precomputed bf16)
//   out_f  = silu_g * (up_i8 * up_scale)
//   out_i8 = clamp(round(out_f * inv_out_scale), -128, 127)
//
// SiLU is a precomputed 256-entry bf16 LUT (gen_silu_lut.py, same
// gate_scale) keyed by the int8 gate input, so the kernel and the numpy
// reference look up bit-identical values -- no HW tanh approximation.
//===----------------------------------------------------------------------===//

#include <aie_api/aie.hpp>
#include <stdint.h>
#include <string.h>

#include "silu_lut.h" // generated by gen_silu_lut.py

#ifndef LLAMA_SILU_MUL_COLS
#define LLAMA_SILU_MUL_COLS 8192 // HIDDEN_DIM
#endif

static constexpr int32_t I8_MAX = 127;
static constexpr int32_t I8_MIN = -128;
static constexpr int kVec = 64;

static inline int8_t round_to_i8(float v) {
  int32_t r = (int32_t)(v + (v >= 0.0f ? 0.5f : -0.5f));
  if (r > I8_MAX)
    r = I8_MAX;
  if (r < I8_MIN)
    r = I8_MIN;
  return (int8_t)r;
}

// See llama_rescale_add.cc for the lane width and vec_round_to_i8.
static constexpr int kLanes = 16;

static inline ::aie::vector<int8, kLanes>
vec_round_to_i8(::aie::vector<float, kLanes> v) {
  ::aie::vector<int32, kLanes> half =
      ::aie::select(::aie::broadcast<int32, kLanes>(0x3f000000),
                    ::aie::broadcast<int32, kLanes>(int32(0xbf000000)),
                    ::aie::lt(v.template cast_to<int32>(), int32(0)));
  ::aie::vector<float, kLanes> t =
      ::aie::add(v, half.template cast_to<float>());
  ::aie::vector<int32, kLanes> n = ::aie::to_fixed<int32>(t, 0);
  ::aie::vector<int32, kLanes> n_bits =
      ::aie::to_float<float>(n, 0).template cast_to<int32>();
  auto away =
      ::aie::lt(::aie::bit_and(int32(0x7fffffff), t.template cast_to<int32>()),
                ::aie::bit_and(int32(0x7fffffff), n_bits));
  ::aie::vector<int32, kLanes> toward_zero = ::aie::select(
      ::aie::add(n, int32(1)), ::aie::sub(n, int32(1)), ::aie::gt(n, int32(0)));
  ::aie::accum<acc32, kLanes> acc;
  acc.from_vector(::aie::select(n, toward_zero, away));
  return acc.template to_vector<int8>(0);
}

static inline bfloat16 silu_lookup(int8_t g) {
  uint16_t raw = llama_silu_lut_raw[(int)g + 128];
  bfloat16 bf;
  memcpy(&bf, &raw, 2);
  return bf;
}

// Software fp32 reciprocal (see llama_flowkv.cc); matches the other
// kernels' sw_recip so numpy and device share it.
static inline float sw_recip(float a) {
  int32_t bits;
  memcpy(&bits, &a, 4);
  bits = (int32_t)0x7EF477D5 - bits;
  float x;
  memcpy(&x, &bits, 4);
  x = x * (2.0f - a * x);
  x = x * (2.0f - a * x);
  x = x * (2.0f - a * x);
  x = x * (2.0f - a * x);
  return x;
}

// s_f * (up_i8 * up_scale), kVec lanes at a time. The LUT gather has no
// AIE2P vector form, so it stays a short scalar loop into a chunk-local
// buffer; everything after that load is an exact widening or an
// elementwise map, so this is bit-identical to the scalar chain per lane
// (see llama_rmsnorm_int8.cc's vec_normalize_chunk for why that holds).
static inline ::aie::vector<float, kVec>
vec_silu_chunk(const int8_t *restrict gate, const int8_t *restrict up,
               ::aie::vector<float, kVec> up_scale_v) {
  bfloat16 s_buf[kVec];
  for (int i = 0; i < kVec; i++)
    s_buf[i] = silu_lookup(gate[i]);
  ::aie::vector<bfloat16, kVec> sv = ::aie::load_v<kVec>(s_buf);
  ::aie::accum<accfloat, kVec> s_acc;
  s_acc.from_vector(sv);
  ::aie::vector<float, kVec> s_f = s_acc.template to_vector<float>();

  ::aie::vector<int8, kVec> uv = ::aie::load_v<kVec>(up);
  ::aie::vector<float, kVec> u_i = ::aie::to_float<float>(uv);
  ::aie::vector<float, kVec> u_f =
      ::aie::mul(u_i, up_scale_v).template to_vector<float>();

  return ::aie::mul(s_f, u_f).template to_vector<float>();
}

extern "C" {

// Dynamic-scale variant (Phase 6c.5b.2). The `up` buffer is sized
// kCols + 8 bytes; the last 8 bytes carry (up_scale fp32, inv_out_scale
// fp32) written by the up-gemm worker upstream. gate_scale stays baked
// into the LUT.
void llama_silu_mul_int8_dyn(int8_t *restrict gate, int8_t *restrict up,
                             int8_t *restrict out) {
  event0();

  constexpr int kCols = LLAMA_SILU_MUL_COLS;
  static_assert(kCols % kVec == 0,
                "LLAMA_SILU_MUL_COLS must be a multiple of 64");
  constexpr int kChunks = kCols / kVec;

  float up_scale, inv_out_scale;
  memcpy(&up_scale, up + kCols, 4);
  memcpy(&inv_out_scale, up + kCols + 4, 4);
  ::aie::vector<float, kVec> up_scale_v =
      ::aie::broadcast<float, kVec>(up_scale);
  ::aie::vector<float, kVec> inv_out_scale_v =
      ::aie::broadcast<float, kVec>(inv_out_scale);

  for (int c = 0; c < kChunks; c++) {
    ::aie::vector<float, kVec> su =
        vec_silu_chunk(gate + c * kVec, up + c * kVec, up_scale_v);
    ::aie::vector<float, kVec> out_f =
        ::aie::mul(su, inv_out_scale_v).template to_vector<float>();
    for (int i = 0; i < kVec; i++)
      out[c * kVec + i] = round_to_i8(out_f[i]);
  }

  event1();
}

// Self-calibrating variant: computes its OWN output scale on-chip (the
// per-token silu_out_scale = down's act_scale) instead of reading
// inv_out_scale from the up tail. Two-pass over s_f*u_f (it holds the whole
// HD vector): pass A finds absmax, pass B requants with inv=sw_recip(absmax/
// 127). Writes silu_out_scale to out[kCols..kCols+4] (out is int8[kCols+8])
// so the downstream down gemm reads its act_scale from the sf tail. Still
// reads up_scale (= up_out_scale, a Phase-2 tiled scale) from the up tail.
void llama_silu_mul_int8_selfcal(int8_t *restrict gate, int8_t *restrict up,
                                 int8_t *restrict out) {
  event0();

  constexpr int kCols = LLAMA_SILU_MUL_COLS;
  static_assert(kCols % kVec == 0,
                "LLAMA_SILU_MUL_COLS must be a multiple of 64");
  constexpr int kChunks = kCols / kVec;

  float up_scale;
  memcpy(&up_scale, up + kCols, 4);
  ::aie::vector<float, kVec> up_scale_v =
      ::aie::broadcast<float, kVec>(up_scale);

  // Pass A: absmax of s_f * u_f (see llama_rmsnorm_int8_dyn for why no
  // fp32 array is kept across loops here).
  float absmax = 0.0f;
  for (int c = 0; c < kChunks; c++) {
    ::aie::vector<float, kVec> su =
        vec_silu_chunk(gate + c * kVec, up + c * kVec, up_scale_v);
    float chunk_max = ::aie::reduce_max(::aie::abs(su));
    if (chunk_max > absmax)
      absmax = chunk_max;
  }
  if (absmax < 1e-12f)
    absmax = 1e-12f;
  float out_scale = absmax * (1.0f / 127.0f);
  float inv_out_scale = sw_recip(out_scale);
  ::aie::vector<float, kVec> inv_out_scale_v =
      ::aie::broadcast<float, kVec>(inv_out_scale);

  // Pass B: recompute + round.
  for (int c = 0; c < kChunks; c++) {
    ::aie::vector<float, kVec> su =
        vec_silu_chunk(gate + c * kVec, up + c * kVec, up_scale_v);
    ::aie::vector<float, kVec> out_f =
        ::aie::mul(su, inv_out_scale_v).template to_vector<float>();
    for (int i = 0; i < kVec; i++)
      out[c * kVec + i] = round_to_i8(out_f[i]);
  }

  memcpy(out + kCols, &out_scale, 4);
  int32_t zero = 0;
  memcpy(out + kCols + 4, &zero, 4);

  event1();
}

// up_requant (Phase 2b self-cal): the up_proj gemm now emits fp32[kCols]; this
// stage computes up_out_scale ON-CHIP (global absmax) and requants to int8,
// writing up_out_scale to out[kCols..kCols+4] (out is int8[kCols+8]) so the
// downstream silu reads up_scale from the up tail (as it already does).
void llama_up_requant(float *restrict up_fp, int8_t *restrict out) {
  event0();
  const ::aie::saturation_mode prev_sat =
      ::aie::swap_saturation(::aie::saturation_mode::saturate);

  constexpr int kCols = LLAMA_SILU_MUL_COLS;
  static_assert(kCols % kLanes == 0,
                "LLAMA_SILU_MUL_COLS must be a multiple of 16");
  constexpr int kChunks = kCols / kLanes;

  // |v| as int32 bits: for non-NaN floats their integer order is the order
  // of the magnitudes.
  ::aie::vector<int32, kLanes> mag = ::aie::zeros<int32, kLanes>();
  for (int c = 0; c < kChunks; c++)
    mag =
        ::aie::max(mag, ::aie::bit_and(int32(0x7fffffff),
                                       ::aie::load_v<kLanes>(up_fp + c * kLanes)
                                           .template cast_to<int32>()));
  int32_t absmax_bits = ::aie::reduce_max(mag);
  float absmax;
  memcpy(&absmax, &absmax_bits, 4);
  if (absmax < 1e-12f)
    absmax = 1e-12f;
  float up_scale = absmax * (1.0f / 127.0f);
  float up_inv = sw_recip(up_scale);
  ::aie::vector<float, kLanes> up_inv_v =
      ::aie::broadcast<float, kLanes>(up_inv);

  for (int c = 0; c < kChunks; c++)
    ::aie::store_v(
        out + c * kLanes,
        vec_round_to_i8(
            ::aie::mul(::aie::load_v<kLanes>(up_fp + c * kLanes), up_inv_v)
                .template to_vector<float>()));

  memcpy(out + kCols, &up_scale, 4);
  int32_t zero = 0;
  memcpy(out + kCols + 4, &zero, 4);
  ::aie::set_saturation(prev_sat);
  event1();
}

} // extern "C"
