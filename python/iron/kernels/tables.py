"""Lookup tables a kernel compiles in, and the C headers that hold them.

The kernel includes the header and its numpy reference reads the same
entries, so the two read identical values.
"""

import numpy as np
from ml_dtypes import bfloat16


def exp_lut(exp_quant_scale: float, low: int = -128) -> np.ndarray:
    """fp32 exp(q * exp_quant_scale) for q from `low` to 127, at lut[q - low].

    A max-shifted score is quantized to q = clamp(round(shifted /
    exp_quant_scale), low, 0) and read here.

    Args:
        exp_quant_scale: The score units of one index step.
        low: The lowest index; a score quantized below it reads lut[0].

    Returns:
        The 128 - `low` entries.
    """
    out = np.zeros(128 - low, dtype=np.float32)
    for k in range(128 - low):
        out[k] = np.exp((k + low) * exp_quant_scale).astype(np.float32)
    return out


def exp_lut_header(exp_quant_scale: float, low: int = -128) -> str:
    """Return the C header holding `exp_lut(exp_quant_scale, low)`.

    Args:
        exp_quant_scale: As for `exp_lut`.
        low: As for `exp_lut`.

    Returns:
        The header: `llama_exp_lut_raw` (the entries' fp32 bits),
        LLAMA_EXP_LUT_LOW and LLAMA_EXP_QUANT_SCALE.
    """
    raw = exp_lut(exp_quant_scale, low).view(np.uint32)
    lines = [
        "// auto-generated by aie.iron.kernels.tables; do not edit",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define LLAMA_EXP_QUANT_SCALE {float(exp_quant_scale)!r}f",
        f"#define LLAMA_EXP_LUT_LOW ({low})",
        f"static const uint32_t llama_exp_lut_raw[{len(raw)}] = {{",
    ]
    for i in range(0, len(raw), 4):
        lines.append(
            "    "
            + ", ".join(f"0x{raw[j]:08x}" for j in range(i, min(i + 4, len(raw))))
            + ","
        )
    lines += ["};"]
    return "\n".join(lines) + "\n"


def silu_lut(gate_scale: float) -> np.ndarray:
    """bf16 silu(i * gate_scale) for every int8 i, at lut[i + 128].

    Args:
        gate_scale: The gate's int8 scale.

    Returns:
        The 256 entries.
    """
    out = np.zeros(256, dtype=bfloat16)
    for raw in range(256):
        x = float(raw - 128) * gate_scale
        out[raw] = bfloat16(x / (1.0 + np.exp(-x)))
    return out


def silu_lut_header(gate_scale: float) -> str:
    """Return the C header holding `silu_lut(gate_scale)`.

    Args:
        gate_scale: As for `silu_lut`.

    Returns:
        The header: `llama_silu_lut_raw`, the entries' bf16 bits.
    """
    raw = silu_lut(gate_scale).view(np.uint16)
    lines = [
        "// auto-generated by aie.iron.kernels.tables; do not edit",
        f"// gate_scale = {gate_scale}",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "static const uint16_t llama_silu_lut_raw[256] = {",
    ]
    for i in range(0, 256, 8):
        lines.append(
            "    " + ", ".join(f"0x{raw[j]:04x}" for j in range(i, i + 8)) + ","
        )
    lines.append("};")
    return "\n".join(lines) + "\n"
