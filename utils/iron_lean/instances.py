@dataclass
class Instance:
    config: Config
    cols: int
    name: str
    export: str
    seq: str

    @property
    def runtime_key(self) -> tuple:
        c = self.config
        return (self.seq, self.cols, c.m, c.k, c.n, c.b_col_maj, c.c_col_maj)

    def params(self) -> str:
        c = self.config
        r, s, t = mac_dims(c.device, c.dtype_in, c.dtype_out, c.emulate)
        return (
            f"{{ rows := {ROWS}, cols := {self.cols}, m := {c.m}, k := {c.k}, n := {c.n}, "
            f"r := {r}, s := {s}, t := {t}, bColMaj := {str(bool(c.b_col_maj)).lower()}, "
            f"cColMaj := {str(bool(c.c_col_maj)).lower()} }}"
        )

    def channels(self) -> list[str]:
        nA = min(ROWS, self.cols)
        return (
            [f"A_L3L2_{i}" for i in range(nA)]
            + [f"B_L3L2_{c}" for c in range(self.cols)]
            + [f"C_L2L3_{c}" for c in range(self.cols)]
        )

    def facts(self) -> list[tuple[str, str]]:
        """The literal division facts the export's index arithmetic needs, with their names."""
        c, cols = self.config, self.cols
        R, NC = ROWS * c.m, c.n * cols
        facts = [
            ("hMt", f"({R} * (Mt : Int)) / {c.m} / {ROWS} = Mt"),
            ("h3", "((Mt : Int) - 3).toNat = Mt - 3"),
            ("hNt", f"({NC} * (Nt : Int)) / {c.n} / {cols} = Nt"),
            ("hKt", f"({c.k} * (Kt : Int)) / {c.k} = Kt"),
            ("hS0", f"({NC} * (Nt : Int) / {c.n} - 1) / {cols} + 1 = Nt"),
        ]
        if cols == 1:
            # simp drops `/ 1` before the slice fact can match; this finishes the job.
            facts.append(("hN1", f"({c.n} * (Nt : Int)) / {c.n} = Nt"))
        facts += [
            (f"hS{j}", f"({NC} * (Nt : Int) / {c.n} - {j} - 1) / {cols} + 1 = Nt")
            for j in range(1, cols)
        ]
        return facts


def export_instance(
    config: Config, cols: int, source: Path = WHOLE_ARRAY, name: str | None = None
) -> Instance:
    """Export `config` at `cols` columns from `source`, as `IronVerify.Instances.<name>`."""
    program = whole_array_program(
        source,
        None,
        config.m,
        config.k,
        config.n,
        cols,
        config.device,
        config.dtype_in,
        config.dtype_out,
        config.b_col_maj,
        config.c_col_maj,
        config.emulate,
    )
    name = name or config.name(cols)
    text = DesignExporter(program, canonical=True, contracts=True).lean(
        name, prefix="IronVerify.Instances"
    )
    text = text.replace(SPDX, f"{SPDX}\n{GENERATED}\n-- {config.source}", 1)
    seq = text[text.index("def seq") : text.index("def design")]
    return Instance(config, cols, name, text, seq)


def streams_module(rep: Instance) -> str:
    facts = rep.facts()
    haves = "".join(f"  have {n} : {f} := by omega\n" for n, f in facts)
    names = ", ".join(n for n, _ in facts)
    theorems = "".join(f"""
theorem ch_{ch} (Mt Kt Nt : Nat) (hM : 0 < Mt) (hK : 0 < Kt) (hN : 0 < Nt) :
    (Instances.{rep.name}.design.seq (p.shapeOf Mt Kt Nt)).stream "{ch}" =
      ((schema p).seq (p.shapeOf Mt Kt Nt)).stream "{ch}" := by
{haves}  wa_stream [p, Instances.{rep.name}.design, Instances.{rep.name}.seq, {names}]
""" for ch in rep.channels())
    return f"""{SPDX}
{GENERATED}

import IronVerify.Schema.Inst.Tactic
import IronVerify.Schema.Instances.{rep.name}

/-! Every shim channel of `{rep.name}` moves the same host elements as `schema p`, for every
shape. Shared by the configurations whose runtime sequence is the same text. -/

namespace IronVerify.Instances.{rep.name}Streams

open IronVerify Schema.WholeArray

set_option linter.unusedSimpArgs false
set_option linter.unusedVariables false
set_option maxRecDepth 20000

def p : Params := {rep.params()}
{theorems}
end IronVerify.Instances.{rep.name}Streams
"""


def check_module(inst: Instance, rep: Instance) -> str:
    c, cols = inst.config, inst.cols
    chans = ", ".join(f'"{ch}"' for ch in inst.channels())
    cases = " | ".join("rfl" for _ in inst.channels())
    bullets = "".join(
        f"  · exact Instances.{rep.name}Streams.ch_{ch} Mt Kt Nt hM hK hN\n"
        for ch in inst.channels()
    )
    streams_import = f"import IronVerify.Schema.Instances.{rep.name}Streams\n"
    return f"""{SPDX}
{GENERATED}

import IronVerify.Schema.Instances.{inst.name}
{streams_import}
/-! `{inst.name}` ({c.source}, {cols} column{"s" if cols > 1 else ""}) is `schema p`. -/

namespace IronVerify.Instances.{inst.name}Check

open IronVerify Schema.WholeArray

set_option maxRecDepth 100000

def p : Params := {inst.params()}

theorem chans_eq : chans p = [{chans}] := by decide

theorem net_eq : Instances.{inst.name}.net.normWalks = (wnet p).normWalks := by decide

theorem kernels_ok : kernelsMatch p Instances.{inst.name}.kernels = true := by decide

theorem every (P : Int × Int × Int) :
    (Instances.{inst.name}.design.seq P).AllChans (· ∈ chans p) := by
  obtain ⟨M, K, N⟩ := P
  rw [chans_eq]
  simp [Instances.{inst.name}.design, Instances.{inst.name}.seq, Seq.AllChans]

theorem chan_streams (Mt Kt Nt : Nat) (hM : 0 < Mt) (hK : 0 < Kt) (hN : 0 < Nt) :
    ∀ ch ∈ chans p, (Instances.{inst.name}.design.seq (p.shapeOf Mt Kt Nt)).stream ch =
      ((schema p).seq (p.shapeOf Mt Kt Nt)).stream ch := by
  intro ch hch
  rw [chans_eq] at hch
  simp only [List.mem_cons, List.not_mem_nil, or_false] at hch
  rcases hch with {cases}
{bullets}
theorem guard : ∀ P : Int × Int × Int, (Instances.{inst.name}.design.seq P).ok = true →
    ∃ Mt Kt Nt : Nat, 0 < Mt ∧ 0 < Kt ∧ 0 < Nt ∧ P = p.shapeOf Mt Kt Nt :=
  guard_of_prefix p {ROWS * c.m} {c.k} {c.n * cols} (by decide) (by decide) (by decide)
    (by decide) (by decide) (by decide) (fun _ _ _ => ⟨_, rfl⟩)

theorem inst : Instance Instances.{inst.name}.design p :=
  ⟨net_eq, Net.pos_of_posB (by decide), Net.pos_of_posB (by decide),
    streams_of_chans every chan_streams, guard⟩

end IronVerify.Instances.{inst.name}Check
"""


def index_module(instances: list[Instance]) -> str:
    imports = "".join(
        f"import IronVerify.Schema.Instances.{i.name}Check\n" for i in instances
    )
    entries = ",\n  ".join(f'"{i.name}"' for i in instances)
    return f"""{SPDX}
{GENERATED}

{imports}
/-! Every shipped whole_array configuration, at every column count of its device, is an
`Instance` of `schema p` (`Instances.<name>Check.inst`), so the schema theorems hold for it. -/

namespace IronVerify.Instances

def all : List String := [
  {entries}]

end IronVerify.Instances
"""


def generate(configs: list[Config], max_cols: int | None) -> dict[Path, str]:
    instances = [
        export_instance(c, cols)
        for c in configs
        for cols in range(1, min(MAX_COLS[c.device], max_cols or 99) + 1)
    ]
    reps: dict[tuple, Instance] = {}
    files: dict[Path, str] = {}
    for inst in instances:
        rep = reps.setdefault(inst.runtime_key, inst)
        files[INSTANCES / f"{inst.name}.lean"] = inst.export
        if rep is inst:
            files[INSTANCES / f"{inst.name}Streams.lean"] = streams_module(inst)
        files[INSTANCES / f"{inst.name}Check.lean"] = check_module(inst, rep)
    files[INDEX] = index_module(instances)
    print(
        f"{len(instances)} instances, {len(reps)} runtime-sequence groups",
        file=sys.stderr,
    )
    return files


def main():
    p = argparse.ArgumentParser()
    p.add_argument(
        "--mode",
        choices=["write", "check"],
        default="write",
        help="write the generated files, or check the committed ones are current",
    )
    p.add_argument(
        "--only",
        nargs="*",
        default=None,
        help="restrict to configurations whose name starts with one of these",
    )
    p.add_argument("--max-cols", type=int, choices=range(1, 9), default=None)
    opts = p.parse_args()

    configs = [
        c
        for c in SHIPPED
        if opts.only is None or any(c.name(1).startswith(o) for o in opts.only)
    ]
    files = generate(configs, opts.max_cols)
    if opts.mode == "write":
        if opts.only is None and opts.max_cols is None:
            shutil.rmtree(LEAN_ROOT / INSTANCES, ignore_errors=True)
        (LEAN_ROOT / INSTANCES).mkdir(parents=True, exist_ok=True)
        for path, text in files.items():
            (LEAN_ROOT / path).write_text(text)
        print(f"wrote {len(files)} files under {LEAN_ROOT / INSTANCES}")
        return
    stale = 0
    committed = {
        p.relative_to(LEAN_ROOT) for p in (LEAN_ROOT / INSTANCES).glob("*.lean")
    } | ({INDEX} if (LEAN_ROOT / INDEX).exists() else set())
    for path in sorted(set(files) | committed):
        new = files.get(path)
        old = (LEAN_ROOT / path).read_text() if path in committed else None
        if new != old:
            stale += 1
            print(f"STALE {path}")
            sys.stdout.writelines(
                list(
                    difflib.unified_diff(
                        (old or "").splitlines(True), (new or "").splitlines(True), n=1
                    )
                )[:20]
            )
    print(f"{len(files) - stale}/{len(files)} instance files current")
    raise SystemExit(1 if stale else 0)


if __name__ == "__main__":
    main()
