"""Generate the schema instances: every shipped whole_array configuration, exported from its live
IRON objects and proved to be `schema p` (IronVerify/IronVerify/Schema/Instances/).

Configurations whose runtime sequences are the same text share their channel proofs: one
`<group>Streams` module per group proves every shim channel, and each instance's `Check` module
proves the fifo graph (`decide`), the kernel contracts' layouts (`decide`), the guards and the
`Instance` itself.
"""

import argparse
import difflib
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path

from export import LEAN_ROOT, SPDX, WHOLE_ARRAY, DesignExporter, whole_array_program
from schema_check import MAX_COLS, ROWS, mac_dims

INSTANCES = Path("IronVerify/Schema/Instances")
INDEX = Path("IronVerify/Schema/Instances.lean")
GENERATED = "-- Generated by utils/iron_lean/instances.py; do not edit."


@dataclass(frozen=True)
class Config:
    """A whole_array configuration an example ships, at every column count its device has."""

    device: str
    dtype_in: str
    dtype_out: str
    m: int
    k: int
    n: int
    b_col_maj: int
    c_col_maj: int
    emulate: int
    source: str

    def name(self, cols: int) -> str:
        flags = (
            ("_bcm" if self.b_col_maj else "")
            + ("_ccm" if self.c_col_maj else "")
            + ("_emu" if self.emulate else "")
        )
        tile = f"{self.m}x{self.k}x{self.n}"
        return f"{self.device}_{self.dtype_in}_{self.dtype_out}_{tile}{flags}_{cols}col"


